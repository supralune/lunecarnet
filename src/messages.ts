export function resolveMessages(locale = "en", overrides: MessageOverrides = {}): ResolvedMessages {
  const defaults = locale.toLowerCase().startsWith("zh") ? zhCnMessages : enMessages;
  return { ...defaults, ...overrides };
}

export function formatMessage(message: string, values: Record<string, string | number> = {}) {
  return message.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}
